use crate::model::PhysicalParams;

/// Belt load-share split for one motor pair. `w` holds the six odd
/// coefficients in order `[I0, I1, V0, V1, C0, C1]`: the constant and
/// position-linear share of the inertial, viscous and coulomb belt forces the
/// endpoint applies antisymmetrically across `first`/`second`.
#[derive(Debug, Clone, PartialEq)]
pub struct PairSplit {
    pub first: usize,
    pub second: usize,
    pub w: [f64; 6],
}

fn fmt_float(x: f64) -> String {
    assert!(x.is_finite(), "profile value must be finite, got {x}");
    let s = format!("{x}");
    if s.contains(['.', 'e', 'E']) {
        s
    } else {
        format!("{s}.0")
    }
}

pub fn render_profile(
    p: &PhysicalParams,
    axes: &[&str],
    modes: &[&str],
    frame: &[Vec<f64>],
    rms_residual: &[f64],
    pairs: &[PairSplit],
) -> String {
    let fmt_vec = |v: &[f64]| {
        let inner: Vec<String> = v.iter().map(|&x| fmt_float(x)).collect();
        format!("[{}]", inner.join(", "))
    };
    let fmt_names = |v: &[&str]| {
        let inner: Vec<String> = v.iter().map(|a| format!("\"{a}\"")).collect();
        format!("[{}]", inner.join(", "))
    };
    let frame_rows: Vec<String> = frame.iter().map(|row| fmt_vec(row)).collect();
    let mut out = format!(
        "# generated by servo-ident; units: torque in 0.1% rated, motion in mm\n\
         version = 3\n\
         axes = {}\n\
         modes = {}\n\
         frame = [{}]\n\
         mass = {}\n\
         viscous = {}\n\
         coulomb = {}\n\
         fit_rms_residual = {}\n",
        fmt_names(axes),
        fmt_names(modes),
        frame_rows.join(", "),
        fmt_vec(&p.mass),
        fmt_vec(&p.viscous),
        fmt_vec(&p.coulomb),
        fmt_vec(rms_residual),
    );
    for ps in pairs {
        let first = axes
            .get(ps.first)
            .unwrap_or_else(|| panic!("pair first slot {} out of range", ps.first));
        let second = axes
            .get(ps.second)
            .unwrap_or_else(|| panic!("pair second slot {} out of range", ps.second));
        out.push_str(&format!(
            "\n[[pair]]\n\
             slots = [\"{first}\", \"{second}\"]\n\
             split_inertial = {}\n\
             split_viscous  = {}\n\
             split_coulomb  = {}\n",
            fmt_vec(&[ps.w[0], ps.w[1]]),
            fmt_vec(&[ps.w[2], ps.w[3]]),
            fmt_vec(&[ps.w[4], ps.w[5]]),
        ));
    }
    out
}

/// `m_diag`: fitted diagonal mass entry, units (0.1% rated) / (mm/s²).
/// `rated_torque_nm`: motor rated torque in N·m.
/// `rot_dist_mm`: linear distance per revolution in mm/rev.
/// `rotor_inertia_kgm2`: rotor moment of inertia in kg·m².
///
/// Returns the drive load-inertia-ratio C00.06 in percent:
/// `(J_total - J_rotor) / J_rotor * 100`.
pub fn c0006_recommendation(
    m_diag: f64,
    rated_torque_nm: f64,
    rot_dist_mm: f64,
    rotor_inertia_kgm2: f64,
) -> f64 {
    let j_total = m_diag * (rated_torque_nm / 1000.0) * rot_dist_mm / (2.0 * std::f64::consts::PI);
    (j_total - rotor_inertia_kgm2) / rotor_inertia_kgm2 * 100.0
}
